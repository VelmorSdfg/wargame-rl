class WarGameEnv(gym.Env):
    metadata = {"render_modes": []}

    def __init__(self, fixed_map_files=None, fixed_map_prob=0.0,
                 action_mode="velocity", n_zones=0, fog=False, opponent=None,
                 scenario_files=None):
        """action_mode: "velocity" — как раньше, (vx,vy) на юнит, Box(n_side*2);
                        "orders"   — MultiDiscrete приказов из ORDERS, исполняются той же
                                     ролевой машинерией, что и у бота (см. _order_move).
        n_zones: сколько точек-объектов ставить (0 = механика выключена). Даёт игре цель, кроме
                 размена: без неё осторожность объективно оптимальна и агент просиживает таймаут.
        fog:     туман войны — враг вне прямой видимости показывается по ПОСЛЕДНЕЙ известной
                 позиции с флагом «не вижу сейчас». Без памяти в политике почти бессмысленно,
                 использовать вместе с RecurrentPPO (train_recurrent.py).
        opponent: None — красными правит реактивный побочный бот (_role_move, как раньше);
                 "scripted" — СКРИПТОВЫЙ РОТНЫЙ: тот же словарь приказов и тот же темп, что у
                 обучаемого (только для action_mode="command"). Именно это надо для честного
                 обучения: реактивный бот не знает про объекты и решает в 12 раз чаще агента;
                 иначе callable(obs_red)->action для self-play (obs_red зеркальный, см. _obs(side=1)).

        ВАЖНО: при значениях по умолчанию размер obs и action НЕ меняется — старые модели грузятся.

        fixed_map_files: список путей-БЕЗ-РАСШИРЕНИЯ к парам (.npy сетка + .json вместимость),
        напр. из maps/crop_tactical.py — реальный вырезанный террейн (с дорогами!) вместо только
        процедурного. fixed_map_prob: вероятность на reset() взять один из них вместо генерации.
        По умолчанию (fixed_map_files=None) поведение НЕ меняется — чистая процедурка, как раньше."""
        super().__init__()
        self.fixed_maps = []
        self._map_cache = {}          # индекс вырезки -> готовая TerrainMap
        for path in (fixed_map_files or []):
            # ВЕКТОРНАЯ карта: рядом лежат собранные поля (vectormap.build). Тогда ни сетки типов,
            # ни поиска связных зданий не нужно — всё посчитано заранее и кладётся как есть.
            if os.path.exists(path + ".fields.npz"):
                import vectormap
                tm, meta = vectormap.load_map(path, M_PER_UNIT)
                span = tm.Gx * tm.cell
                if abs(span - ARENA) > ARENA * 0.05:
                    print(f"ВНИМАНИЕ: карта {os.path.basename(path)} покрывает {span:.0f} игр.ед "
                          f"при поле {ARENA:.0f}. Пересоберите под этот масштаб: "
                          f"py -3.12 vectormap.py {path}.vector.json --cell "
                          f"{ARENA * M_PER_UNIT / tm.Gx:.0f}")
                self._map_cache[len(self.fixed_maps)] = tm
                self.fixed_maps.append((None, tm.cell, tm.building_capacity))
                continue
            grid = np.load(path + ".npy")
            with open(path + ".json", "r", encoding="utf-8") as f:
                meta = json.load(f)
            cap = {int(k): v for k, v in meta.get("building_capacity", {}).items()}
            # ВАЖНО: meta["cell_m"] — РЕАЛЬНЫЕ метры (как считал maps/segment_reference.py), а вся
            # позиционная арифметика в WarGameEnv — в ИГРОВЫХ единицах (ARENA=100, 1ед.=M_PER_UNIT м).
            # Без деления TerrainMap.cell окажется в 70 раз крупнее, чем нужно — вся арена схлопнется
            # в один угол сетки (баг: "монотонное поле", вся карта грузится в 1 клетку из 140).
            cell_units = meta["cell_m"] / M_PER_UNIT
            # Вырезка делалась под конкретный масштаб. Если он не совпадает с текущим m_per_unit,
            # сетка окажется крупнее или мельче арены, и в бою будет использован лишь угол карты
            # (или наоборот, карта не покроет поле). Молча это делать нельзя — предупреждаем.
            span = grid.shape[0] * cell_units
            if abs(span - ARENA) > ARENA * 0.05:
                print(f"ВНИМАНИЕ: вырезка {os.path.basename(path)} рассчитана на другой масштаб — "
                      f"её сетка покрывает {span:.0f} игр.ед при поле {ARENA:.0f}. "
                      f"Клетка {meta['cell_m']:.0f} м при текущем m_per_unit={M_PER_UNIT:.0f}. "
                      f"Нужны вырезки под этот масштаб (maps/crop_platoon.py).")
            self.fixed_maps.append((grid, cell_units, cap))
        self.fixed_map_prob = fixed_map_prob if self.fixed_maps else 0.0

        self.n_side = len(FORCE)           # число юнитов на сторону = длина наряда
        self.n = self.n_side * 2           # слоты 0..n_side-1 свои, дальше враги
        self.types = list(FORCE) + list(FORCE)
        # ЮНИТ-уровень (оборона/подвижность) — массивы по слотам
        self.max_hp = np.array([STATS[t]["hp"] for t in self.types], dtype=np.float32)
        self.speed = np.array([STATS[t]["speed"] for t in self.types], dtype=np.float32)
        self.armor = np.array([STATS[t]["armor"] for t in self.types], dtype=np.float32)
        self.sg = np.array([STATS[t]["sg"] for t in self.types], dtype=np.float32)
        self.sr = np.array([STATS[t]["sr"] for t in self.types], dtype=np.float32)
        self.friendly = np.array([i < self.n_side for i in range(self.n)], dtype=bool)

        # ОРУЖИЕ (offensive) — список оружий на каждый слот; у каждого своя перезарядка
        WKEYS = ("rng", "minrng", "dmg", "acc", "pen", "soft", "cd")
        self.weapons = []
        for t in self.types:
            wl = [{k: float(w[k]) for k in WKEYS}
                  | {# ДАЛЬНОСТЬ СТРЕЛЬБЫ (rng) И ДАЛЬНОСТЬ ПОРАЖЕНИЯ (lethal) — РАЗНЫЕ ВЕЩИ.
                     # До lethal ствол наносит полный урон; дальше урон падает до dmg_far на
                     # предельной. Так автомат и пулемёт могут доставать одинаково далеко, но
                     # автомат за 800 м только прижимает, а убивает метров до двухсот. Подавление
                     # при этом с дальностью почти не падает — очередь рядом пугает одинаково.
                     "lethal": float(w.get("lethal", w["rng"])),
                     "dmg_far": float(w.get("dmg_far", 1.0)),   # доля урона на предельной дальности
                     "suppr": float(w.get("suppr", 0.25)),      # подавление за попадание
                     "move_acc": float(w.get("move_acc", MOVE_ACC)),  # точность с ходу
                     "name": w.get("name", "?"), "vs_soft": bool(w.get("vs_soft", True)),
                     "demolish": bool(w.get("demolish", False)),   # может вести огонь по зданиям
                     "min_crew": int(w.get("min_crew", 1)),        # ниже этой численности расчёт выбит
                     "deploy": int(w.get("deploy", 0)),           # шагов на месте до развёртывания
                     # Боекомплект задан В ПАТРОНАХ (как в Wargame: Red Dragon), а наша единица
                     # действия — выстрел за шаг в 10 с. Поэтому число выстрелов ВЫВОДИТСЯ, а не
                     # задаётся руками: так видно, откуда взялась цифра, и её можно проверить.
                     "rounds": float(w.get("ammo_rounds", 10 ** 6)),
                     "per_shot": float(w.get("rounds_per_shot", 1.0)),
                     "ammo": max(1, int(float(w.get("ammo_rounds", 10 ** 6))
                                        / float(w.get("rounds_per_shot", 1.0))))}
                  for w in STATS[t]["weapons"]]
            self.weapons.append(wl)
        # численность отделения; живых выводим из HP, отдельного состояния не заводим
        self.crew = np.array([float(STATS[t].get("crew", 1)) for t in self.types], dtype=np.float32)
        self.wcd = [np.array([w["cd"] for w in wl], dtype=np.float32) for wl in self.weapons]  # cd стволов
        # удобные производные по слотам: rng = макс. дальность юнита; minrng — у самого дальнобойного ствола
        self.rng = np.array([max(w["rng"] for w in wl) for wl in self.weapons], dtype=np.float32)
        # ЭФФЕКТИВНАЯ дальность = самая дальняя, на которой юнит ещё наносит полный урон. Все
        # ТАКТИЧЕСКИЕ решения (куда идти, где встать, с какой дистанции держать под огнём)
        # считаются по ней, а не по rng. Иначе, уравняв дальность автомата и пулемёта, мы бы
        # получили отделения, замирающие в километре от противника: формально «в радиусе», а
        # фактически безвредные. Обнаружение при этом остаётся по rng — видеть можно дальше,
        # чем убивать.
        # Считаем ТОЛЬКО по стволам, работающим по живой силе: РПГ-7 с кумулятивным БК по пехоте
        # не стреляет, и его 495 м не должны задавать дистанцию боя стрелковому отделению —
        # иначе оно встанет там, где реально может только смотреть.
        self.eff_rng = np.array([max((w["lethal"] for w in wl if w["vs_soft"]),
                                     default=max(w["lethal"] for w in wl))
                                 for wl in self.weapons], dtype=np.float32)
        self.minrng = np.array([max(wl, key=lambda w: w["rng"])["minrng"] for wl in self.weapons],
                               dtype=np.float32)

        # эталонные сценарии (scenario.py): фиксированная вырезка + расставленные вручную зоны
        # и позиции сторон. Для ЗАМЕРОВ, не для обучения — на 15 сценариях агент их просто заучит.
        self.scenarios = []
        for path in (scenario_files or []):
            import scenario as _sc
            self.scenarios.append(_sc.load(path))

        # разбивка слотов на элементы по РОЛИ — одинаково для обеих сторон (симметрия важна:
        # иначе «сковать танковый противника» значило бы не то же, что видит красная сторона)
        self.elements = {0: self._build_elements(0), 1: self._build_elements(1)}
        self.n_elements = len(ORDER_OF_BATTLE)

        self.action_mode = action_mode
        self.n_zones = int(n_zones)
        self.fog = bool(fog)
        self.opponent = opponent

        # исходный боекомплект — для доли в наблюдении и для отрисовки «9/24» в карточке
        self._ammo0 = [np.array([max(w["ammo"], 1) for w in wl], dtype=np.float32) for wl in self.weapons]

        self.n_sense = terrain.TerrainMap.N_SENSE_DIRS
        # 8 база + 1 дорога + 1 личный состав + 1 боекомплект + 1 изготовка + 1 «с ходу» + лучи
        self.obs_per_unit = 13 + self.n_sense
        if self.fog:
            self.obs_per_unit += 1            # +1 флаг «вижу сейчас» (0 => позиция последняя известная)
        obs_dim = self.n * self.obs_per_unit + 3 * self.n_zones   # на зону: x, y, чья (-1/0/+1)
        if action_mode == "command":
            # на СВОЙ элемент 9 чисел: задача, объект, направление, возраст приказа, доля живых,
            # доля HP, центр x/y, подавленность. Приказ и его возраст в obs — ОБЯЗАТЕЛЬНО: приказы липкие, и без
            # них политика не знает, что скомандовала сама, т.е. не может дать манёвру доиграть.
            # На вражеский элемент 5: доля живых, доля HP, центр x/y, подавленность.
            obs_dim += self.n_elements * (9 + 5) + self.N_TACTICAL
        self.observation_space = spaces.Box(-1.0, 2.0, shape=(obs_dim,), dtype=np.float32)
        if action_mode == "command":
            # голова «объект» полиморфна: 0..base-1 — зоны/элементы, дальше коды ориентиров
            self.lm_base = max(self.n_zones, self.n_elements)
            n_obj = self.lm_base + len(LANDMARKS)
            self.n_obj = n_obj
            self.action_space = spaces.MultiDiscrete(
                [len(TASKS), n_obj, len(AXES)] * self.n_elements)
        elif action_mode == "orders":
            self.action_space = spaces.MultiDiscrete([len(ORDERS)] * self.n_side)
        elif action_mode == "velocity":
            self.action_space = spaces.Box(-1.0, 1.0, shape=(self.n_side * 2,), dtype=np.float32)
        else:
            raise ValueError(f"action_mode: 'velocity' | 'orders' | 'command', получено {action_mode!r}")

    # ------------------------------------------------------------------ элементы
    def _build_elements(self, side):
        """side 0 = синие (слоты 0..n_side-1), 1 = красные. Возвращает список списков слотов —
        по одному на элемент из ORDER_OF_BATTLE, в том же порядке. Обе стороны нарезаются
        одинаково: иначе «сковать 2-й мсв противника» значило бы не то, что видит красная сторона."""
        base = 0 if side == 0 else self.n_side
        out, k = [], 0
        for el in ORDER_OF_BATTLE:
            out.append([base + k + j for j in range(len(el["units"]))])
            k += len(el["units"])
        return out

    def _element_slots(self, side, e):
        return self.elements[side][e]

    def _element_alive(self, side, e):
        return [i for i in self._element_slots(side, e) if self.alive[i]]

    def _deploy_ready(self, i):
        """Изготовка юнита i: 0 — расчёт ещё не развёрнут, 1 — развёрнут полностью.

        Считаем по САМОМУ ДОЛГОМУ стволу, которым юнит реально может работать (расчёт цел):
        отделение готово тогда, когда готово его главное оружие. У кого разворачивать нечего
        (автоматы) — сразу 1, иначе автоматчики выглядели бы вечно неготовыми."""
        need = max((w["deploy"] for w in self.weapons[i]
                    if self.crew_alive(i) >= w["min_crew"]), default=0)
        return 1.0 if need <= 0 else float(min(self._settle[i] / need, 1.0))

    def _element_center(self, side, e):
        live = self._element_alive(side, e)
        return self.pos[live].mean(axis=0) if live else None

    def _element_nearest(self, i, side, e, reach=0.0):
        """Точка для огня по элементу e глазами юнита i: ПРЕДПОЧТИТЕЛЬНО тот его юнит, который
        отсюда виден и достижим, иначе просто ближайший.

        Две причины, обе из замеров. Во-первых, не центр масс: линия огня до центроида открыта
        в 0% случаев против 9-15% до реальных юнитов на той же дальности — центроид разнесённого
        элемента систематически попадает в лес или за гребень, где никого нет и куда не видно.
        Во-вторых, выбор с учётом видимости обязателен: прицельный огонь перебирает ВСЕХ врагов
        и стреляет в того, кого видно, а площадной привязан к ОДНОЙ точке. При видимости ~10%
        привязка к ближайшему давала ноль выстрелов — цель почти всегда оказывалась закрыта."""
        live = self._element_alive(side, e)
        if not live:
            return None
        p = self._last_seen[0 if self.friendly[i] else 1] if self.fog else self.pos
        d = {k: float(np.linalg.norm(p[k] - self.pos[i])) for k in live}
        if reach > 0.0:
            seen = [k for k in live
                    if d[k] <= reach and not self.map.blocked(self.pos[i], p[k])]
            if seen:
                return p[min(seen, key=d.get)].copy()
        return p[min(live, key=d.get)].copy()

    # ------------------------------------------------------------------ helpers
    def _obs(self, side=0):
        """side=0 — глазами синих (как всегда было). side=1 — глазами КРАСНЫХ, для self-play:
        «мои» юниты переставлены в начало, координаты зеркалированы по Y (стороны спавнятся
        у противоположных краёв), лучи препятствий переставлены соответственно повороту.
        Так одна и та же политика может играть за обе стороны, не переучиваясь на новую геометрию."""
        mine = self.friendly if side == 0 else ~self.friendly
        # при тумане враги вне видимости показываются по ПОСЛЕДНЕЙ известной позиции
        pos = self._last_seen[side] if self.fog else self.pos

        o = np.zeros((self.n, self.obs_per_unit), dtype=np.float32)
        o[:, 0] = pos[:, 0] / ARENA
        o[:, 1] = pos[:, 1] / ARENA
        o[:, 2] = np.where(self.alive, self.hp / self.max_hp, 0.0)
        o[:, 3] = self.suppr
        o[:, 4] = self.alive.astype(np.float32)
        o[:, 5] = mine.astype(np.float32)
        o[:, 6] = [self.map.cover_at(pos[k]) for k in range(self.n)]  # укрытие подо мной
        o[:, 7] = [float(1.0 - np.mean(self.reload[k] / self.wcd[k])) if self.alive[k] else 0.0
                   for k in range(self.n)]  # готовность оружия (1 = все стволы заряжены)
        o[:, 8] = [self.map.speed_at(pos[k], self.armor[k] > 0) if self.alive[k] else 0.0
                   for k in range(self.n)]  # множитель скорости подо мной (>1 = дорога — тем для агента и видно)
        # доля личного состава: по ней видно, какие стволы у отделения уже потеряны (см. crew_alive)
        o[:, 9] = [self.crew_alive(k) / self.crew[k] if self.alive[k] else 0.0 for k in range(self.n)]
        # доля оставшегося боекомплекта: без неё командир не может решить, кого беречь, а кому
        # разрешить жечь патроны на подавление
        o[:, 10] = [float(np.mean(self.ammo[k] / self._ammo0[k])) if self.alive[k] else 0.0
                    for k in range(self.n)]
        # ИЗГОТОВКА расчёта: 0 — только встал, 1 — развёрнут и бьёт в полную силу. Правило было
        # и раньше (неразвёрнутый расчётный ствол бьёт с множителем DEPLOY_ACC), но его СОСТОЯНИЕ
        # в наблюдение не попадало: оно есть в среде и даже в реплее, а модель его не видела.
        # Из-за этого «дай пулемётному изготовиться, потом атакуй» было невыучиваемо в принципе —
        # ждать нечего, если готовность не наблюдаема.
        o[:, 11] = [self._deploy_ready(k) if self.alive[k] else 0.0 for k in range(self.n)]
        # «стрелял с ходу»: точность режется вдвое (MOVE_ACC). Тот же класс, что и изготовка —
        # правило действует, а причину увидеть было нельзя.
        o[:, 12] = [float(self._moved[k]) if self.alive[k] else 0.0 for k in range(self.n)]
        # лучи-дистанции до препятствия вокруг юнита (1=чисто, 0=вплотную) — "чувство стены впереди"
        s0 = 13
        for k in range(self.n):
            o[k, s0:s0 + self.n_sense] = (self.map.sense_obstacles(pos[k], self.armor[k] > 0)
                                          if self.alive[k] else 0.0)
        if self.fog:
            o[:, s0 + self.n_sense] = self._vis[side].astype(np.float32)  # 1 = вижу сейчас

        if side == 1:                                    # зеркалим геометрию под красных
            o[:, 1] = 1.0 - o[:, 1]                                        # y -> ARENA - y
            o[:, s0:s0 + self.n_sense] = o[:, s0:s0 + self.n_sense][:, _SENSE_YFLIP]
            o = np.concatenate([o[self.n_side:], o[:self.n_side]], axis=0)  # мои — в начало

        flat = o.reshape(-1)
        if self.n_zones:
            own = self._zone_owner()                     # +1 = за синих, -1 = за красных
            zx = self.zones[:, 0] / ARENA
            zy = self.zones[:, 1] / ARENA
            if side == 1:
                zy = 1.0 - zy
                own = -own                               # «моя» зона у красных — это -1 в мире
            flat = np.concatenate([flat, np.stack([zx, zy, own], axis=1).reshape(-1)]).astype(np.float32)
        if self.action_mode == "command":
            flat = np.concatenate([flat, self._element_obs(side),
                                   self._tactical_obs(side)]).astype(np.float32)
        return flat

    N_TACTICAL = 14

    def _tactical_obs(self, side):
        """ОБСТАНОВКА одним блоком: то, что живой командир оценивает в первую очередь.

        Считается правилами и подаётся готовым. Без этого командир видит только координаты
        двух десятков юнитов и обязан выводить из них соотношение сил и наличие соприкосновения
        сам — то есть тратить ёмкость сети на то, что вычисляется тремя строками."""
        foe = 1 - side
        mine = self.friendly if side == 0 else ~self.friendly
        ours = mine & self.alive
        theirs = (~mine) & self.alive
        n_o, n_t = int(ours.sum()), int(theirs.sum())

        hp_o = float(np.mean(self.hp[ours] / self.max_hp[ours])) if n_o else 0.0
        hp_t = float(np.mean(self.hp[theirs] / self.max_hp[theirs])) if n_t else 0.0
        ratio = n_o / max(n_o + n_t, 1)                     # 0.5 = равенство сил
        ammo = float(np.mean([np.mean(self.ammo[k] / self._ammo0[k]) for k in np.nonzero(ours)[0]])) if n_o else 0.0
        pinned = float(sum(1 for k in np.nonzero(ours)[0]
                           if self.suppr[k] >= SUPPR_PINNED)) / max(n_o, 1)
        # ДОЛЯ ПРИЖАТЫХ У ПРОТИВНИКА — сводный сигнал «сейчас момент». Был только свой.
        foe_pinned = float(sum(1 for k in np.nonzero(theirs)[0]
                               if self.suppr[k] >= SUPPR_PINNED)) / max(n_t, 1)
        # соприкосновение: доля наших, у кого есть ОБНАРУЖЕННЫЙ противник в пределах своей дальности
        contact = float(sum(1 for k in np.nonzero(ours)[0] if (self._acq[k] >= 1.0).any())) / max(n_o, 1)
        # объекты: сколько наших и сколько чужих
        if self.n_zones:
            own = self._zone_owner() * (1.0 if side == 0 else -1.0)
            z_mine = float((own > 0).sum()) / self.n_zones
            z_foe = float((own < 0).sum()) / self.n_zones
        else:
            z_mine = z_foe = 0.0
        # МИНОМЁТЫ: сколько вызовов осталось и летит ли сейчас. Без этого решение «тратить или
        # приберечь» невыучиваемо — модель не видит ни запаса, ни того, что огонь уже в пути,
        # и заказывала бы повторно вслепую. Признаки СВОЕЙ стороны: side задаёт, чьи именно.
        m_left = float(self._mortar_left[side]) / max(MORTAR_CALLS, 1)
        m_fly = 1.0 if (self._mortar_q[side, :, 0] >= 0).any() else 0.0
        # ЗАДАЧА: наступаю я или обороняюсь, и насколько рубеж уже удержан — мной и противником.
        # Без этого один и тот же командир не может учиться обеим задачам: он не видит, какая
        # перед ним стоит, и выучит одну усреднённую линию поведения.
        attacking = 1.0 if self.mission == side else 0.0
        hold_me = min(self._hold[side] / max(MISSION_HOLD, 1), 1.0) if self.n_zones else 0.0
        hold_foe = min(self._hold[1 - side] / max(MISSION_HOLD, 1), 1.0) if self.n_zones else 0.0
        return np.array([ratio, hp_o, hp_t, ammo, pinned, contact, z_mine, z_foe,
                         m_left, m_fly, foe_pinned, attacking, hold_me, hold_foe],
                        dtype=np.float32)

    def _element_obs(self, side):
        """Блок по элементам: свои — с ТЕКУЩИМ ПРИКАЗОМ и его возрастом, чужие — только состав.

        Приказ в наблюдении обязателен, потому что приказы липкие: без него политика не помнит,
        что скомандовала сама, и липкость выродится в случайное переназначение задач."""
        foe = 1 - side
        rows = []
        for e in range(self.n_elements):
            t, o, x = (int(v) for v in self._orders[side, e])
            if side == 1:
                # ВАЖНО: зеркалирование по Y — это ОТРАЖЕНИЕ, оно меняет лево и право местами.
                # «Обход слева» в мировых координатах для красных в зеркальном виде обязан
                # выглядеть как «справа», иначе политика за красных учится на перевёрнутой
                # геометрии — молча, без единой ошибки в логах. Тест инварианта это ловит.
                x = len(AXES) - 1 - x
            live = self._element_alive(side, e)
            slots = self._element_slots(side, e)
            frac = len(live) / max(len(slots), 1)
            hp = float(np.mean(self.hp[live] / self.max_hp[live])) if live else 0.0
            c = self._element_center(side, e)
            cx = c[0] / ARENA if c is not None else 0.0
            cy = c[1] / ARENA if c is not None else 0.0
            if side == 1 and c is not None:
                # ВАЖНО: только когда центр ЕСТЬ. У выбитого элемента cy=0.0 как «нет данных»,
                # и отражение превратило бы это в 1.0, т.е. в «элемент у верхнего края» —
                # признак отсутствия стал бы признаком позиции. Тест инварианта поймал именно это.
                cy = 1.0 - cy                       # зеркалим так же, как позиции юнитов
            # ПОДАВЛЕННОСТЬ элемента — среднее по живым. Приказы адресуются ЭЛЕМЕНТАМ, а признак
            # был только в поюнитном блоке: политике пришлось бы самой сопоставлять слоты с
            # индексами элементов в голове приказа. На ротном масштабе, где в элементе несколько
            # юнитов, это вообще потребовало бы агрегации внутри сети.
            sup = float(np.mean(self.suppr[live])) if live else 0.0
            rows.append([t / max(len(TASKS) - 1, 1), o / max(self.n_obj - 1, 1),
                         x / max(len(AXES) - 1, 1),
                         min(self._order_age[side, e] / MAX_STEPS, 1.0),
                         frac, hp, cx, cy, sup])
        for e in range(self.n_elements):
            live = self._element_alive(foe, e)
            slots = self._element_slots(foe, e)
            frac = len(live) / max(len(slots), 1)
            hp = float(np.mean(self.hp[live] / self.max_hp[live])) if live else 0.0
            c = self._element_center(foe, e)
            cx = c[0] / ARENA if c is not None else 0.0
            cy = c[1] / ARENA if c is not None else 0.0
            if side == 1 and c is not None:
                # ВАЖНО: только когда центр ЕСТЬ. У выбитого элемента cy=0.0 как «нет данных»,
                # и отражение превратило бы это в 1.0, т.е. в «элемент у верхнего края» —
                # признак отсутствия стал бы признаком позиции. Тест инварианта поймал именно это.
                cy = 1.0 - cy
            # То же по элементу ПРОТИВНИКА, и здесь это важнее всего: «он прижат» — сигнал,
            # по которому решают штурмовать. Прижатый (suppr>=SUPPR_PINNED) не воюет и не
            # маневрирует, то есть момент для рывка. Без этого признака момент не наблюдаем.
            sup = float(np.mean(self.suppr[live])) if live else 0.0
            rows.append([frac, hp, cx, cy, sup])
        return np.concatenate([np.asarray(r, dtype=np.float32) for r in rows])

    def _zone_owner(self):
        """Кто держит каждую зону: +1 синие, -1 красные, 0 — ничья/пусто. По большинству живых
        юнитов в радиусе ZONE_RADIUS — простое и предсказуемое правило, без таймеров захвата."""
        out = np.zeros(self.n_zones, dtype=np.float32)
        for z in range(self.n_zones):
            d = np.linalg.norm(self.pos - self.zones[z], axis=1)
            inz = self.alive & (d <= ZONE_RADIUS)
            b = int((inz & self.friendly).sum())
            r = int((inz & ~self.friendly).sum())
            out[z] = 1.0 if b > r else (-1.0 if r > b else 0.0)
        return out

    def _update_fog(self):
        """Пересчёт видимости для обеих сторон. Свои видны всегда; враг виден, если хоть один
        живой свой имеет к нему чистую линию в пределах SIGHT_RADIUS. Невидимый враг «замирает»
        в obs на последней известной позиции — поэтому без памяти в политике толку мало."""
        for s in (0, 1):
            mine = self.friendly if s == 0 else ~self.friendly
            watchers = np.nonzero(mine & self.alive)[0]
            for k in range(self.n):
                if mine[k]:
                    self._vis[s, k] = True
                    self._last_seen[s, k] = self.pos[k]
                    continue
                seen = False
                if self.alive[k]:
                    for i in watchers:
                        if (np.linalg.norm(self.pos[k] - self.pos[i]) <= SIGHT_RADIUS
                                and not self.map.blocked(self.pos[i], self.pos[k])):
                            seen = True
                            break
                self._vis[s, k] = seen
                if seen:
                    self._last_seen[s, k] = self.pos[k]

